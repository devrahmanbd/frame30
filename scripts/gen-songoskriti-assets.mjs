#!/usr/bin/env node
/**
 * Songoskriti imagery generator — spec §4.
 *
 * Generates the raster assets of the shared manifest
 * (scripts/songoskriti-assets-manifest.mjs) via the Gemini Imagen REST API.
 * The brand file (logo-lockup.svg) is hand-built and committed directly, so
 * the manifest marks it `generated: false` and this script never writes it.
 *
 *   POST https://generativelanguage.googleapis.com/v1beta/models/gemini-3-pro-image:generateContent
 *
 * Security (non-negotiable):
 *   - The key is read ONLY from process.env.GEMINI_API_KEY, and ONLY on the
 *     generation path. The key check lives in the generation path, never at
 *     module scope, so `--check` runs offline with no key in the environment.
 *   - The key is NEVER logged, printed (not even a prefix), persisted, or
 *     written to disk. It travels only in the Authorization header of the
 *     Imagen request.
 *
 * Behaviour:
 *   - Retry ×2 per asset (3 attempts total), then skip-on-fail with a warning
 *     — the storefront fallback (file-if-exists else /api/public/ph) covers
 *     missing files, so one failed asset never fails the whole run.
 *   - Idempotent: an existing file whose BYTES carry the manifest's format is
 *     skipped unless --force. The skip is format-aware: a .jpg asset is not
 *     treated as absent just because its bytes are not a PNG.
 *   - The bytes the API returns must match the format the file NAME claims.
 *     JPEG bytes under a .png name are refused before they reach the disk —
 *     that drift is exactly what the acceptance gate exists to catch.
 *   - `--check` needs no key and no network: it compares the plan with the
 *     manifest, the manifest with the frozen expectation (names AND
 *     formats), and the expectation with the tree (format, geometry, digest)
 *     — and it reports a file the expectation does not name.
 *   - Do NOT run until the owner confirms the key rotation.
 *
 * Usage:
 *   GEMINI_API_KEY=... node scripts/gen-songoskriti-assets.mjs [--force] [--out public/ph/songoskriti]
 *   node scripts/gen-songoskriti-assets.mjs --check   # keyless + offline: the three legs above
 *   node scripts/songoskriti-assets-check.mjs          # gate: GREEN when complete
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { ASSETS, ASSET_DIR } from "./songoskriti-assets-manifest.mjs";
import { fileInfo, imageInfo } from "./songoskriti-assets-image.mjs";

const ENDPOINT =
  "https://generativelanguage.googleapis.com/v1beta/models/gemini-3-pro-image:generateContent";
const MAX_ATTEMPTS = 3; // initial try + retry x2

/** The frozen expectation the approved artifacts are compared against. */
const EXPECTATION_PATH = resolve(
  import.meta.dirname,
  "songoskriti-assets-expected.json",
);

const argv = process.argv.slice(2);
const FORCE = argv.includes("--force");
const CHECK = argv.includes("--check");
const outFlag = argv.indexOf("--out");
const OUT = resolve(
  import.meta.dirname,
  "..",
  outFlag === -1 ? ASSET_DIR : argv[outFlag + 1],
);

/**
 * The format a file NAME claims — the claim, not the truth about the bytes.
 */
function expectedFormatFor(name) {
  if (name.endsWith(".jpg")) return "jpeg";
  if (name.endsWith(".png")) return "png";
  return "svg";
}

/**
 * Refuse bytes whose format contradicts the file name they would be written
 * under. This is the guard against the drift that shipped nine JPEG assets
 * under .png names.
 *
 * @param {string} name the file name the bytes would be written under
 * @param {Buffer} bytes the bytes the image API returned
 */
export function assertFormatMatches(name, bytes) {
  const info = imageInfo(bytes);
  const expected = expectedFormatFor(name);
  if (!info.format) {
    throw new Error(`unreadable image bytes for ${name}`);
  }
  if (info.format !== expected) {
    throw new Error(
      `format mismatch for ${name}: bytes are ${info.format}, name says ${expected}`,
    );
  }
}

/**
 * Write generated bytes to the target directory — but only after the name and
 * the bytes agree on their format.
 *
 * @param {string} name the file name under the target directory
 * @param {Buffer} bytes the bytes the image API returned
 */
export function writeAssetBytes(name, bytes) {
  assertFormatMatches(name, bytes);
  writeFileSync(resolve(OUT, name), bytes);
}

/**
 * The plan the generator intends to satisfy: every manifest entry, in
 * manifest order. The hand-built brand asset is part of the plan (it ships
 * under the same name and is covered by the same expectation) but it is
 * never generated, so its aspect is reported as `n/a`.
 *
 * @returns {{name: string, aspect: string, format: string}[]}
 */
export function buildPlan() {
  return ASSETS.map((a) => ({
    name: a.name,
    aspect: a.aspect ?? "n/a",
    format: a.format,
  }));
}

/**
 * Is the file on disk already the artifact the manifest entry describes?
 *
 * The check is format-aware: a `.jpg` entry is satisfied by JPEG bytes —
 * the nine renamed assets — which the old PNG-only check treated as absent
 * and then overwrote.
 *
 * @param {{format: string}} entry the manifest entry
 * @param {{format: string | null} | null} info what `fileInfo` reports
 * @returns {boolean} true when the file is present with the right format
 */
export function isUpToDate(entry, info) {
  return Boolean(info) && info.format === entry.format;
}

/**
 * The files in a directory that a set of approved names does not cover — an
 * orphan the standalone check must not ignore.
 *
 * @param {string} dir the directory to list
 * @param {string[]} approvedNames the names the expectation approves
 * @returns {string[]} the unapproved file names, sorted
 */
export function findExtraFiles(dir, approvedNames) {
  if (!existsSync(dir)) return [];
  if (!statSync(dir).isDirectory()) return [];
  const approved = new Set(approvedNames);
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => !approved.has(name))
    .sort();
}

/**
 * Compare two asset sets — arrays of `{name, format}` — on BOTH the name and
 * the format. The format is part of an asset's identity: the manifest's
 * format is authoritative, so a manifest that declares a different format
 * than the expectation is a defect, not a rename.
 *
 * @param {{name: string, format: string}[]} left the first set
 * @param {{name: string, format: string}[]} right the second set
 * @param {string} leftLabel how the first set is named in the messages
 * @param {string} rightLabel how the second set is named in the messages
 * @returns {string[]} one message per difference
 */
export function diffAssetSets(left, right, leftLabel, rightLabel) {
  const leftMap = new Map(left.map((entry) => [entry.name, entry.format]));
  const rightMap = new Map(right.map((entry) => [entry.name, entry.format]));
  const problems = [];
  for (const [name, format] of leftMap) {
    if (!rightMap.has(name)) {
      problems.push(
        `${leftLabel} has ${name} (${format}) but ${rightLabel} does not`,
      );
      continue;
    }
    const other = rightMap.get(name);
    if (other === format) continue;
    problems.push(
      `${leftLabel} declares ${name} as ${format} but ${rightLabel} declares it as ${other}`,
    );
  }
  for (const [name, format] of rightMap) {
    if (leftMap.has(name)) continue;
    problems.push(
      `${rightLabel} has ${name} (${format}) but ${leftLabel} does not`,
    );
  }
  return problems;
}

/**
 * The key is read here and nowhere else. `--check` never reaches this
 * function, so the check mode needs neither a key nor a network.
 */
function requireApiKey() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error(
      "GEMINI_API_KEY is not set. Export it in the environment (never commit it) " +
        "and re-run. Generation is blocked until the owner confirms key rotation.",
    );
  }
  return apiKey;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function generateOnce(prompt, aspectRatio, apiKey) {
  const res = await fetch(ENDPOINT, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      // The key is used here only, in the request header — never logged.
      "x-goog-api-key": apiKey,
    },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        responseModalities: ["TEXT", "IMAGE"],
        imageConfig: { aspectRatio },
      },
    }),
  });
  if (!res.ok) throw new Error(`Imagen HTTP ${res.status}`);
  const data = await res.json();
  const parts = data?.candidates?.[0]?.content?.parts ?? [];
  const img = parts.find((p) => p.inlineData?.data);
  if (!img) throw new Error("Imagen returned no image bytes");
  return Buffer.from(img.inlineData.data, "base64");
}

async function generateAsset(entry, apiKey) {
  const { name, aspect, prompt } = entry;
  const path = resolve(OUT, name);
  const existing = fileInfo(path);
  // Format-aware: a .jpg asset is present when its bytes are JPEG.
  if (!FORCE && isUpToDate(entry, existing)) {
    console.log(
      `skip (exists ${existing.width}x${existing.height} ${existing.format}): ${name}`,
    );
    return "skipped";
  }
  let lastError = null;
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      const bytes = await generateOnce(prompt, aspect, apiKey);
      // The write refuses bytes whose format contradicts the name.
      writeAssetBytes(name, bytes);
      console.log(`ok: ${name} (${bytes.length} bytes)`);
      return "ok";
    } catch (error) {
      lastError = error;
      console.warn(`warn: ${name} attempt ${attempt} failed: ${error.message}`);
      await sleep(1000 * attempt);
    }
  }
  // Skip-on-fail: the file-if-exists else /api/public/ph fallback covers it.
  console.warn(
    `warn: skipping ${name} after ${MAX_ATTEMPTS} attempts (${lastError?.message}). ` +
      `Fallback art covers this asset.`,
  );
  return "failed";
}

/**
 * The keyless, offline check. Three legs:
 *
 *   1. plan ↔ manifest — an identity by construction (the plan is built
 *      from the manifest); it is printed so the operator sees exactly what a
 *      run would produce, and compared so the tripwire fires if that changes.
 *   2. manifest ↔ expectation — names AND formats must match exactly. The
 *      manifest's format is authoritative.
 *   3. expectation ↔ tree — format, geometry and digest must match, and the
 *      output directory must hold the expected set and nothing else.
 */
function runCheck() {
  const plan = buildPlan();
  const expected = JSON.parse(readFileSync(EXPECTATION_PATH, "utf8"));
  const problems = [];

  // Leg 1 — plan ↔ manifest.
  const planDiff = diffAssetSets(plan, ASSETS, "the plan", "the manifest");
  if (planDiff.length > 0) {
    problems.push("plan does not cover the manifest");
    problems.push(...planDiff);
  }

  // Leg 2 — manifest ↔ expectation (names and formats).
  const expectationDiff = diffAssetSets(
    ASSETS,
    expected.assets,
    "the manifest",
    "the expectation",
  );
  if (expectationDiff.length > 0) {
    problems.push("expectation does not match the manifest");
    problems.push(...expectationDiff);
  }

  // Leg 3 — expectation ↔ tree.
  for (const rec of expected.assets) {
    const info = fileInfo(resolve(OUT, rec.name));
    if (!info) {
      problems.push(`missing: ${rec.name}`);
      continue;
    }
    if (info.format !== rec.format) {
      problems.push(
        `format differs from the expectation: ${rec.name} is ${info.format}, the expectation says ${rec.format}`,
      );
    }
    if (info.width !== rec.width || info.height !== rec.height) {
      problems.push(`geometry differs from the expectation: ${rec.name}`);
    }
    if (info.sha256 !== rec.sha256) {
      problems.push(`digest differs from the expectation: ${rec.name}`);
    }
  }

  // The output directory holds the expected set and nothing else.
  const approvedNames = expected.assets.map((a) => a.name);
  for (const name of findExtraFiles(OUT, approvedNames)) {
    problems.push(`extra file in the output directory: ${name}`);
  }

  for (const p of plan) console.log(`plan ${p.name} ${p.aspect} ${p.format}`);
  if (problems.length > 0) {
    console.error(
      `songoskriti asset check RED — ${problems.length} problem(s):`,
    );
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log(
    `songoskriti asset check GREEN — ${plan.length} planned assets match the expectation.`,
  );
  process.exit(0);
}

/**
 * The generation path. The key is required HERE, after the check mode has
 * had its chance to run without one.
 */
async function runGeneration() {
  const apiKey = requireApiKey();
  mkdirSync(OUT, { recursive: true });
  const results = [];
  for (const asset of ASSETS.filter((a) => a.generated)) {
    results.push(await generateAsset(asset, apiKey));
    await sleep(4000); // gentle pacing across assets (free-tier quota)
  }
  const failed = results.filter((r) => r === "failed").length;
  console.log(
    `done: ${results.length - failed}/${results.length} generated` +
      (failed ? `, ${failed} skipped-on-fail (fallback covers them)` : ""),
  );
}

async function runCli() {
  if (CHECK) {
    runCheck();
    return;
  }
  await runGeneration();
}

const cliEntry = process.argv[1] ? pathToFileURL(process.argv[1]).href : null;
if (import.meta.url === cliEntry) {
  await runCli();
}
