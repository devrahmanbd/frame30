#!/usr/bin/env bun
/**
 * Phase 10.5 — builds the single local icon sprite (TODO §10.5 bullet 2).
 *
 * Source of truth is `ICON_NAMES` in `src/lib/marketing-assets.ts`; geometry
 * comes from the installed `lucide-react` icon nodes, so the marks are the real
 * lucide paths at the real 24px grid rather than hand-traced approximations.
 * Output is `public/media/icons/sprite.svg`: one `<symbol>` per name, sorted by
 * name so the file is byte-deterministic and a rebuild produces no diff when
 * nothing changed (a churning binary in git is how sprites stop being rebuilt).
 *
 * Operational behaviour:
 *   • `--check` verifies the on-disk sprite matches what we would build now and
 *     exits 1 if not, so CI catches "added an icon, forgot the sprite".
 *   • a name lucide does not know is reported by name, and every missing name is
 *     collected before exiting — one run tells you all of them.
 *   • the byte budget from `ICONS.maxBytes` is enforced here too, not only in
 *     the browser gate, so an oversized sprite never reaches a branch.
 *   • JSONL logs on stderr, human summary on stdout, exit 0/1/2 (clean /
 *     contract failure / harness failure).
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";

const argv = process.argv.slice(2);
const has = (f) => argv.includes(`--${f}`);
const CHECK = has("check");
const ROOT = resolve(import.meta.dirname, "..");

const log = (level, event, fields = {}) =>
  process.stderr.write(
    `${JSON.stringify({ ts: new Date().toISOString(), level, gate: "icons", event, ...fields })}\n`,
  );

function attrs(record) {
  return Object.entries(record)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${key}="${String(value).replace(/"/g, "&quot;")}"`)
    .join(" ");
}

async function main() {
  const { ICON_NAMES, ICONS, SPRITE_PATH } = await import(`${ROOT}/src/lib/marketing-assets.ts`);
  /**
   * Path data comes from the per-icon ESM modules (`__iconNode`), not from the
   * `lucide-react` barrel. In this version the barrel exports forwardRef
   * components whose only keys are `$$typeof`/`render`: the geometry is simply
   * not reachable from them, which is why every one of the 30 names reported as
   * "unknown". Loading `dist/esm/icons/<kebab>.js` also keeps the build off the
   * 5,800-export barrel, so the sprite build stays fast.
   */
  const iconNodeFor = async (name) => {
    try {
      const mod = await import(`lucide-react/dist/esm/icons/${name}.js`);
      return Array.isArray(mod.__iconNode) ? mod.__iconNode : null;
    } catch {
      return null;
    }
  };

  const missing = [];
  const symbols = [];

  for (const name of [...ICON_NAMES].sort()) {
    const iconNode = await iconNodeFor(name);
    if (!Array.isArray(iconNode)) {
      missing.push(name);
      continue;
    }
    const children = iconNode
      .map(([tag, props]) => `<${tag} ${attrs(props)} />`)
      .join("");
    symbols.push(
      `<symbol id="${name}" viewBox="${ICONS.viewBox}" fill="none" stroke="currentColor" ` +
        `stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${children}</symbol>`,
    );
  }

  if (missing.length > 0) {
    log("error", "icons.unknown_names", { missing });
    console.error(
      `icon sprite FAILED: lucide has no icon for ${missing.length} name(s): ${missing.join(", ")}`,
    );
    process.exit(1);
  }

  const sprite =
    `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none">` +
    `<!-- generated by scripts/build-icon-sprite.mjs — do not edit -->` +
    symbols.join("") +
    `</svg>\n`;

  const target = resolve(ROOT, `public${SPRITE_PATH}`);
  const bytes = Buffer.byteLength(sprite, "utf8");

  if (bytes > ICONS.maxBytes) {
    log("error", "icons.oversize", { bytes, budget: ICONS.maxBytes });
    console.error(
      `icon sprite FAILED: ${Math.round(bytes / 1024)}KB exceeds the ${Math.round(
        ICONS.maxBytes / 1024,
      )}KB budget — prune ICON_NAMES.`,
    );
    process.exit(1);
  }

  if (CHECK) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current === sprite) {
      console.log(`icon sprite up to date — ${symbols.length} symbols, ${Math.round(bytes / 1024)}KB.`);
      return;
    }
    log("error", "icons.stale", { target });
    console.error(
      `icon sprite FAILED: ${SPRITE_PATH} is ${current === null ? "missing" : "stale"}. ` +
        `Run \`bun run assets:icons\`.`,
    );
    process.exit(1);
  }

  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, sprite, "utf8");
  log("info", "icons.written", { target, symbols: symbols.length, bytes });
  console.log(
    `icon sprite written — ${symbols.length} symbols, ${Math.round(bytes / 1024)}KB → public${SPRITE_PATH}`,
  );
}

main().catch((error) => {
  log("error", "icons.harness_failed", { message: String(error?.message ?? error) });
  console.error(`icon sprite harness failed: ${error?.stack ?? error}`);
  process.exit(2);
});
